    OSWALD("Oswald"),
    PLAYFAIR_DISPLAY("Playfair Display"),
    PLAYWRITE_IT_TRAD("Playwrite IT Trad"),
    ROBOTO_MONO("Roboto Mono"),
    TUFFY("Tuffy"),
}
